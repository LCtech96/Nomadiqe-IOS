-- Create the table safely if it doesn't exist yet
CREATE TABLE IF NOT EXISTS public.referrals (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    referrer_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    referred_user_id UUID UNIQUE REFERENCES public.profiles(id) ON DELETE CASCADE,
    referred_user_role TEXT NOT NULL CHECK (referred_user_role IN ('host', 'creator', 'jolly', 'manager')), 
    source_platform VARCHAR(100) DEFAULT 'direct', 
    referral_type VARCHAR(50) DEFAULT 'points' NOT NULL CHECK (referral_type IN ('points', 'commission', 'non-commission')),
    points_awarded INT DEFAULT 0 NOT NULL,
    commission_amount NUMERIC(10, 2) DEFAULT 0.00 NOT NULL,
    payout_status VARCHAR(50) DEFAULT 'n/a' NOT NULL CHECK (payout_status IN ('n/a', 'pending', 'approved', 'paid')),
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- Safely create indexes if they don't exist
CREATE INDEX IF NOT EXISTS referrals_referrer_idx ON public.referrals(referrer_id);
CREATE INDEX IF NOT EXISTS referrals_source_idx ON public.referrals(source_platform);

-- Enable RLS
ALTER TABLE public.referrals ENABLE ROW LEVEL SECURITY;

-- Drop policy if it exists first so the script never throws an error on rerun
DROP POLICY IF EXISTS "Users can view their own referrals" ON public.referrals;
CREATE POLICY "Users can view their own referrals"
  ON public.referrals FOR SELECT
  USING (auth.uid() = referrer_id);

-- ============================================
-- Host property share links (referral + personal)
-- Commission links for creators; personal links for guests (no commission).
-- ============================================

CREATE TABLE IF NOT EXISTS public.host_share_links (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    host_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    link_type TEXT NOT NULL CHECK (link_type IN ('commission', 'personal')),
    slug TEXT NOT NULL UNIQUE,
    property_id UUID REFERENCES public.properties(id) ON DELETE SET NULL,
    creator_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    creator_name TEXT,
    creator_email TEXT,
    commission_percent NUMERIC(5, 2) CHECK (
        commission_percent IS NULL
        OR (commission_percent >= 0 AND commission_percent <= 100)
    ),
    internal_label TEXT,
    guest_message VARCHAR(280),
    click_count INT DEFAULT 0 NOT NULL,
    booking_count INT DEFAULT 0 NOT NULL,
    is_hidden BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

CREATE INDEX IF NOT EXISTS host_share_links_host_idx ON public.host_share_links(host_id);
CREATE INDEX IF NOT EXISTS host_share_links_slug_idx ON public.host_share_links(slug);
CREATE INDEX IF NOT EXISTS host_share_links_type_idx ON public.host_share_links(host_id, link_type);

ALTER TABLE public.host_share_links ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Hosts manage own share links" ON public.host_share_links;
CREATE POLICY "Hosts manage own share links"
  ON public.host_share_links FOR ALL
  TO authenticated
  USING (auth.uid() = host_id)
  WITH CHECK (auth.uid() = host_id);

COMMENT ON TABLE public.host_share_links IS 'Referral (commission) and personal share links generated by hosts for properties';